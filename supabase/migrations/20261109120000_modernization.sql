-- SECAP: solicitações de modernização (modelo do painel em Apps Script).
-- Execute depois de 20261105120000_secap.sql, no SQL Editor ou com `supabase db push`.
-- Leitura: somente o administrador (RLS). Escrita: somente pelas funções mod_*, que
-- conferem o administrador, aplicam as regras do modelo e gravam o histórico na mesma transação.

create table if not exists public.modernization_requests (
  protocol text primary key check (protocol ~ '^SECAP-[0-9]{4}-[0-9]{5,}$'),
  created_at timestamptz not null default now(),
  requester_email text not null check (position('@' in requester_email) > 1 and char_length(requester_email) <= 254),
  requester_name text not null check (char_length(requester_name) between 1 and 120),
  registration text not null default '' check (char_length(registration) <= 20),
  department text not null check (char_length(department) between 1 and 150),
  solution_type text not null check (char_length(solution_type) between 1 and 120),
  title text not null check (char_length(title) between 1 and 200),
  description text not null check (char_length(description) between 1 and 20000),
  status text not null default 'Solicitado'
    check (status in ('Solicitado', 'Em execução', 'Cancelada', 'Concluída')),
  updated_at timestamptz not null default now(),
  updated_by text not null default '',
  rating smallint check (rating between 1 and 5),
  rating_label text,
  rating_comment text check (rating_comment is null or char_length(rating_comment) <= 500)
);

create table if not exists public.modernization_history (
  id bigint generated by default as identity primary key,
  protocol text not null references public.modernization_requests (protocol) on delete cascade,
  created_at timestamptz not null default now(),
  event text not null,
  previous_status text not null default '',
  new_status text not null default '',
  actor_email text not null default '',
  actor_name text not null default '',
  note text not null default ''
);

create table if not exists public.modernization_seq (
  year integer primary key,
  last integer not null
);

create index if not exists modernization_requests_status_idx on public.modernization_requests (status);
create index if not exists modernization_requests_email_idx on public.modernization_requests (lower(requester_email));
create index if not exists modernization_history_protocol_idx on public.modernization_history (protocol);

alter table public.modernization_requests enable row level security;
alter table public.modernization_history enable row level security;
alter table public.modernization_seq enable row level security;

drop policy if exists modernization_requests_admin_read on public.modernization_requests;
create policy modernization_requests_admin_read on public.modernization_requests
  for select to authenticated using (public.is_admin());

drop policy if exists modernization_history_admin_read on public.modernization_history;
create policy modernization_history_admin_read on public.modernization_history
  for select to authenticated using (public.is_admin());

revoke all on public.modernization_requests from anon, authenticated;
revoke all on public.modernization_history from anon, authenticated;
revoke all on public.modernization_seq from anon, authenticated;
grant select on public.modernization_requests to authenticated;
grant select on public.modernization_history to authenticated;

-- Mesma normalização do painel original: quebras de linha unificadas e bordas sem espaço.
create or replace function public.mod_text(v text)
returns text
language sql
immutable
set search_path = public
as $$
  select regexp_replace(
    replace(replace(coalesce(v, ''), E'\r\n', E'\n'), E'\r', E'\n'),
    '^\s+|\s+$', '', 'g'
  );
$$;

create or replace function public.mod_detail(p_protocol text)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'request', (select to_jsonb(r) from public.modernization_requests r where r.protocol = p_protocol),
    'history', coalesce((
      select jsonb_agg(to_jsonb(h) order by h.created_at, h.id)
      from public.modernization_history h where h.protocol = p_protocol
    ), '[]'::jsonb)
  );
$$;

create or replace function public.mod_create_request(p jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_name text := public.mod_text(p->>'requester_name');
  v_email text := lower(public.mod_text(p->>'requester_email'));
  v_reg text := public.mod_text(p->>'registration');
  v_dep text := public.mod_text(p->>'department');
  v_type text := public.mod_text(p->>'solution_type');
  v_title text := regexp_replace(public.mod_text(p->>'title'), '\s*\n\s*', ' ', 'g');
  v_desc text := public.mod_text(p->>'description');
  v_actor_email text;
  v_actor_name text;
  v_year integer;
  v_seq integer;
  v_protocol text;
begin
  if not public.is_admin() then
    raise exception 'Acesso restrito ao administrador.';
  end if;
  if char_length(v_name) not between 3 and 120 then
    raise exception 'Nome do solicitante: informe entre 3 e 120 caracteres.';
  end if;
  if v_email !~ '^[^\s@]+@[^\s@]+\.[^\s@]+$' or char_length(v_email) > 254 then
    raise exception 'E-mail do solicitante: informe um endereço válido.';
  end if;
  if char_length(v_reg) not between 3 and 20 then
    raise exception 'Matrícula: informe entre 3 e 20 caracteres.';
  end if;
  if char_length(v_dep) not between 2 and 150 then
    raise exception 'Lotação: informe entre 2 e 150 caracteres.';
  end if;
  if char_length(v_type) not between 1 and 120 then
    raise exception 'Tipo de solução: selecione uma opção da lista.';
  end if;
  if char_length(v_title) not between 10 and 80 then
    raise exception 'Título / Assunto do pedido: informe entre 10 e 80 caracteres (atualmente %).', char_length(v_title);
  end if;
  if char_length(v_desc) not between 1000 and 5000 then
    raise exception 'Descrição do serviço / Observações: informe entre 1.000 e 5.000 caracteres (atualmente %).', char_length(v_desc);
  end if;

  select email, coalesce(nullif(name, ''), email) into v_actor_email, v_actor_name
  from public.profiles where id = auth.uid();

  v_year := extract(year from (now() at time zone 'America/Sao_Paulo'))::integer;
  loop
    insert into public.modernization_seq (year, last) values (v_year, 1)
    on conflict (year) do update set last = public.modernization_seq.last + 1
    returning last into v_seq;
    v_protocol := 'SECAP-' || v_year || '-' || lpad(v_seq::text, 5, '0');
    exit when not exists (select 1 from public.modernization_requests where protocol = v_protocol);
  end loop;

  insert into public.modernization_requests
    (protocol, requester_email, requester_name, registration, department, solution_type, title, description, updated_by)
  values (v_protocol, v_email, v_name, v_reg, v_dep, v_type, v_title, v_desc, v_actor_email);
  insert into public.modernization_history (protocol, event, new_status, actor_email, actor_name)
  values (v_protocol, 'Criação da solicitação', 'Solicitado', v_actor_email, v_actor_name);
  return public.mod_detail(v_protocol);
end;
$$;

create or replace function public.mod_change_status(p_protocol text, p_new text, p_expected text, p_note text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_protocol text := upper(public.mod_text(p_protocol));
  v_note text := public.mod_text(p_note);
  v_current text;
  v_actor_email text;
  v_actor_name text;
begin
  if not public.is_admin() then
    raise exception 'Acesso restrito ao administrador.';
  end if;
  if v_protocol !~ '^SECAP-[0-9]{4}-[0-9]{5,}$' then
    raise exception 'Protocolo inválido. Use o formato SECAP-AAAA-NNNNN.';
  end if;
  if p_new is null or p_new not in ('Solicitado', 'Em execução', 'Cancelada', 'Concluída') then
    raise exception 'Selecione um status válido: Solicitado, Em execução, Cancelada, Concluída.';
  end if;
  if char_length(v_note) > 1000 then
    raise exception 'Observação: o limite é de 1000 caracteres. Resuma o texto.';
  end if;
  select status into v_current from public.modernization_requests where protocol = v_protocol for update;
  if not found then
    raise exception 'Solicitação não encontrada. Atualize a lista e tente novamente.';
  end if;
  if coalesce(p_expected, '') <> '' and p_expected <> v_current then
    raise exception 'Esta solicitação foi alterada enquanto você a visualizava (status atual: "%"). Feche e abra os detalhes novamente antes de alterar.', v_current;
  end if;
  if v_current = p_new then
    raise exception 'A solicitação já está com o status "%". Escolha um status diferente.', p_new;
  end if;
  if (p_new = 'Cancelada' or v_current in ('Cancelada', 'Concluída')) and char_length(v_note) < 10 then
    raise exception 'Observação: informe a justificativa (mínimo de 10 caracteres). Ela é obrigatória ao cancelar ou ao reabrir uma solicitação concluída ou cancelada.';
  end if;

  select email, coalesce(nullif(name, ''), email) into v_actor_email, v_actor_name
  from public.profiles where id = auth.uid();
  update public.modernization_requests
  set status = p_new, updated_at = now(), updated_by = v_actor_email
  where protocol = v_protocol;
  insert into public.modernization_history (protocol, event, previous_status, new_status, actor_email, actor_name, note)
  values (v_protocol, 'Alteração de status', v_current, p_new, v_actor_email, v_actor_name, v_note);
  return public.mod_detail(v_protocol);
end;
$$;

create or replace function public.mod_rate_request(p_protocol text, p_rating integer, p_comment text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_protocol text := upper(public.mod_text(p_protocol));
  v_comment text := public.mod_text(p_comment);
  v_status text;
  v_rating smallint;
  v_label text;
  v_actor_email text;
  v_actor_name text;
begin
  if not public.is_admin() then
    raise exception 'Acesso restrito ao administrador.';
  end if;
  if v_protocol !~ '^SECAP-[0-9]{4}-[0-9]{5,}$' then
    raise exception 'Protocolo inválido. Use o formato SECAP-AAAA-NNNNN.';
  end if;
  if p_rating is null or p_rating not between 1 and 5 then
    raise exception 'Avaliação: selecione uma das cinco opções da escala de satisfação.';
  end if;
  if char_length(v_comment) > 500 then
    raise exception 'Comentário: o limite é de 500 caracteres. Resuma o texto.';
  end if;
  select status, rating into v_status, v_rating
  from public.modernization_requests where protocol = v_protocol for update;
  if not found then
    raise exception 'Solicitação não encontrada. Atualize a lista e tente novamente.';
  end if;
  if v_status <> 'Concluída' then
    raise exception 'A avaliação fica disponível somente depois que a solicitação é concluída.';
  end if;
  if v_rating is not null then
    raise exception 'Esta solicitação já foi avaliada.';
  end if;
  v_label := case p_rating
    when 1 then 'Muito insatisfeito' when 2 then 'Insatisfeito' when 3 then 'Neutro'
    when 4 then 'Satisfeito' else 'Muito satisfeito' end;
  select email, coalesce(nullif(name, ''), email) into v_actor_email, v_actor_name
  from public.profiles where id = auth.uid();
  update public.modernization_requests
  set rating = p_rating, rating_label = v_label, rating_comment = v_comment,
      updated_at = now(), updated_by = v_actor_email
  where protocol = v_protocol;
  insert into public.modernization_history (protocol, event, previous_status, new_status, actor_email, actor_name, note)
  values (v_protocol, 'Avaliação registrada', 'Concluída', 'Concluída', v_actor_email, v_actor_name,
          'Nota ' || p_rating || ' – ' || v_label || ' (registrada pelo administrador em nome do solicitante)');
  return public.mod_detail(v_protocol);
end;
$$;

-- p_replace = true: restauração de backup (substitui tudo). false: migração (só protocolos novos).
create or replace function public.mod_import(p_requests jsonb, p_history jsonb, p_replace boolean default false)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_added text[];
begin
  if not public.is_admin() then
    raise exception 'Acesso restrito ao administrador.';
  end if;
  if jsonb_typeof(p_requests) is distinct from 'array' or jsonb_typeof(coalesce(p_history, '[]'::jsonb)) is distinct from 'array' then
    raise exception 'Solicitações do backup inválidas.';
  end if;
  if p_replace then
    delete from public.modernization_history where true;
    delete from public.modernization_requests where true;
    delete from public.modernization_seq where true;
  end if;

  with incoming as (
    select * from jsonb_to_recordset(p_requests) as r(
      protocol text, created_at timestamptz, requester_email text, requester_name text, registration text,
      department text, solution_type text, title text, description text, status text,
      updated_at timestamptz, updated_by text, rating integer, rating_label text, rating_comment text)
  ), ins as (
    insert into public.modernization_requests
      (protocol, created_at, requester_email, requester_name, registration, department, solution_type,
       title, description, status, updated_at, updated_by, rating, rating_label, rating_comment)
    select upper(public.mod_text(protocol)), created_at, lower(public.mod_text(requester_email)),
      public.mod_text(requester_name), public.mod_text(registration), public.mod_text(department),
      public.mod_text(solution_type), public.mod_text(title), public.mod_text(description), status,
      coalesce(updated_at, created_at), public.mod_text(updated_by),
      case when rating between 1 and 5 then rating end,
      case rating when 1 then 'Muito insatisfeito' when 2 then 'Insatisfeito' when 3 then 'Neutro'
        when 4 then 'Satisfeito' when 5 then 'Muito satisfeito' end,
      case when rating between 1 and 5 then public.mod_text(rating_comment) end
    from incoming
    on conflict (protocol) do nothing
    returning protocol
  )
  select coalesce(array_agg(protocol), '{}') into v_added from ins;

  insert into public.modernization_history
    (protocol, created_at, event, previous_status, new_status, actor_email, actor_name, note)
  select upper(public.mod_text(h.protocol)), h.created_at, public.mod_text(h.event),
    public.mod_text(h.previous_status), public.mod_text(h.new_status), public.mod_text(h.actor_email),
    public.mod_text(h.actor_name), public.mod_text(h.note)
  from jsonb_to_recordset(coalesce(p_history, '[]'::jsonb)) as h(
    protocol text, created_at timestamptz, event text, previous_status text, new_status text,
    actor_email text, actor_name text, note text)
  where upper(public.mod_text(h.protocol)) = any (v_added)
    and h.created_at is not null and public.mod_text(h.event) <> '';

  insert into public.modernization_seq (year, last)
  select substring(protocol from 7 for 4)::integer, max(substring(protocol from 12)::integer)
  from public.modernization_requests
  group by 1
  on conflict (year) do update set last = greatest(public.modernization_seq.last, excluded.last);

  return coalesce(cardinality(v_added), 0);
exception
  when check_violation or not_null_violation or invalid_text_representation or invalid_datetime_format then
    raise exception 'Solicitações do backup inválidas.';
end;
$$;

